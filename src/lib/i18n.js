export const getInitialLanguage = () => {
  const saved = localStorage.getItem('wishlist_language');
  if (supportedLanguages.some((language) => language.code === saved)) return saved;

  const browserLanguage = navigator.language?.slice(0, 2);
  if (supportedLanguages.some((language) => language.code === browserLanguage)) return browserLanguage;

  return defaultLanguage;
};

export const getLanguageMeta = (languageCode) => (
  supportedLanguages.find((language) => language.code === languageCode) || supportedLanguages[0]
);

export const createTranslator = (languageCode) => {
  const dictionary = translations[languageCode] || translations[defaultLanguage];
  const fallback = translations[defaultLanguage];
  const englishFallback = translations.en;

  return (key) => {
    const path = key.split('.');
    let value = dictionary;
    let fallbackValue = fallback;
    let englishValue = englishFallback;

    path.forEach((part) => {
      value = value?.[part];
      fallbackValue = fallbackValue?.[part];
      englishValue = englishValue?.[part];
    });

    return value || englishValue || fallbackValue || key;
  };
};
