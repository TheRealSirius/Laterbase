export const getCurrencyMeta = (languageCode) => currencyByLanguage[languageCode] || currencyByLanguage[defaultLanguage];

export const createMoneyFormatter = (languageCode) => {
  const { code, locale } = getCurrencyMeta(languageCode);
  const needsCurrencyCode = ['JPY', 'CNY'].includes(code);
  const formatter = new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: code,
    maximumFractionDigits: ['JPY', 'KRW', 'IDR', 'HUF'].includes(code) ? 0 : 2,
  });

  return (value) => {
    const formatted = formatter.format(Number(value) || 0);
    return needsCurrencyCode ? `${formatted} ${code}` : formatted;
  };
};

