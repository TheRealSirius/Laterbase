const mergeTranslations = (base, patch) => {
  Object.entries(patch).forEach(([key, value]) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      base[key] = mergeTranslations(base[key] || {}, value);
    } else {
      base[key] = value;
    }
  });
  return base;
};

